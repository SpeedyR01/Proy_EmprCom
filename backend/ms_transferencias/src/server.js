import express from "express";
import cors from "cors";
import dotenv from "dotenv";
import transferenciasRoutes from "./transferencias.routes.js";
dotenv.config();
const app = express();
app.use(cors());
app.use(express.json());
app.get("/", (_req, res) => res.json({ servicio: "ms-transferencias", ok: true }));
app.use("/transferencias", transferenciasRoutes);
const PORT = process.env.PORT || 4005;
app.listen(PORT, () => console.log(`ms-transferencias en http://localhost:${PORT}`));